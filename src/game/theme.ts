export let theme = menu

export function applyTheme(name: keyof typeof palettes): void {
  theme = palettes[name]
  document.documentElement.style.backgroundColor = theme.bg
  document.documentElement.style.setProperty('--game-glow', theme.glow)
  for (const key of ['text', 'muted', 'surface', 'outline', 'hint', 'correct', 'button', 'buttonSecondary'] as const) {
    document.documentElement.style.setProperty(`--game-${key}`, theme[key])
  }
  document.querySelector('meta[name="theme-color"]')?.setAttribute('content', theme.bg)
}
